/**
 * سجلّ الكتب — نقطة التوسّع الوحيدة عند إضافة كتاب جديد
 * ---------------------------------------------------------------
 * البيانات نفسها تعيش في `data/books.registry.json` (JSON خالص) لا
 * في هذا الملف، لأن لوحة الإدارة (/admin) تكتب فيها برمجياً عند
 * إضافة كتاب أو حذفه — وتعديل ملف JS بالكود هشّ. هذا الملف يبقى
 * الواجهة التي تستوردها السكربتات، فلم يتغيّر شيء عندها.
 *
 * يمكنك تحرير الـ JSON يدوياً كما كنت تحرّر هذه القائمة. حقول المدخلة:
 *
 * docx     : اسم ملف Word في مجلد books/ — هو مصدر النصّ
 * slug     : المعرّف في الرابط (لاتيني ليبقى الرابط نظيفاً عند المشاركة)
 * overrides: تصحيح العنوان/العنوان الفرعي/النبذة حين يخطئ الغلاف.
 *            اتركه محذوفاً ليُستخرج العنوان آلياً من الغلاف.
 * accent   : لون الغلاف المميّز — يُمزج مع الذهب في الغلاف المولَّد
 * tags     : وسوم التصفية في صفحة المكتبة
 * order    : ترتيب العرض في المكتبة
 *
 * بعد أي تعديل يدوي:
 *     npm run ingest    # النصّ والفهرس
 *     npm run pdf       # ملف التنزيل (يحتاج Word على ويندوز)
 *
 * أو استعمل لوحة الإدارة على /admin فتقوم بالخطوتين عنك.
 */

