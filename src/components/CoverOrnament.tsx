/**
 * زخرفة الغلاف — نخيلة عربية (Palmette)
 * ---------------------------------------------------------------
 * زخرفة نباتية مستوحاة من تذهيب المخطوطات العربية وفواصل الكتب
 * المطبوعة الكلاسيكية: ورقة مركزية بينها فرعان يتلويان إلى حلزون،
 * وخطّان رفيعان يمتدان إلى الحاشية.
 *
 * لماذا نباتية لا هندسية؟ الزخرفة النباتية (الأرابيسك) هي معجم
 * الكتاب الفخم — تُقرأ كترف وأناقة، بلا أي إيحاء رمزي.
 *
 * الشريط أفقي (100×40) لأنه يجلس فوق العنوان كفاصلة زخرفية،
 * وهذا أفضل من مربّع يزاحم العنوان على المساحة.
 *
 * `variant` يبدّل عنصر التزيين حول النواة، فتبدو الأغلفة سلسلة
 * واحدة دون أن تتطابق.
 */

interface Props {
  variant: number;
  className?: string;
}

export function CoverOrnament({ variant, className }: Props) {
  const v = variant % 4;

  return (
    <svg
      viewBox="0 0 100 40"
      className={className}
      fill="none"
      stroke="currentColor"
      strokeWidth="0.9"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {/* الورقة المركزية */}
      <path d="M50 5 C 55.5 12 56 20.5 50 29 C 44 20.5 44.5 12 50 5 Z" />
      <path d="M50 9.5 V 26" strokeWidth="0.5" />

      {/* الفرعان الملتويان + الخطّان الممتدان — نصف واحد يُعكس مرآةً */}
      {[1, -1].map((side) => (
        <g key={side} transform={side === 1 ? undefined : 'translate(100,0) scale(-1,1)'}>
          {/* الفرع: يخرج من أسفل الورقة، يصعد، ثم يلتفّ حلزوناً */}
          <path d="M50 28.5 C 41 30 34 27 29.5 20.5 C 27.5 17.5 23.5 16.5 21 19 C 18.8 21.2 20.2 24.6 23.2 24.2" />
          {/* ورقة صغيرة على الفرع */}
          <path d="M36.5 26.4 C 34.5 22.6 35.6 19.6 38.6 18.4 C 39.4 21.8 38.8 24.6 36.5 26.4 Z" />
          {/* الخطّ الممتدّ إلى الحاشية */}
          <path d="M27 29.5 H 6" strokeWidth="0.55" />

          {v === 0 && <circle cx="4" cy="29.5" r="1.15" fill="currentColor" stroke="none" />}
          {v === 1 && <path d="M4.6 27.6 L 6.4 29.5 L 4.6 31.4 L 2.8 29.5 Z" strokeWidth="0.55" />}
          {v === 2 && (
            <>
              <path d="M24 32.6 H 9" strokeWidth="0.4" />
              <circle cx="6.6" cy="31" r="0.85" fill="currentColor" stroke="none" />
            </>
          )}
          {v === 3 && (
            <path d="M6 29.5 C 6 26.4 8.4 24.6 11.4 25.4 C 10 28.8 8.2 30.2 6 29.5 Z" strokeWidth="0.55" />
          )}
        </g>
      ))}

      {/* نقطة التاج فوق الورقة */}
      <circle cx="50" cy="3" r="1.05" fill="currentColor" stroke="none" />
    </svg>
  );
}
